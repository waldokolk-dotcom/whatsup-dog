import fs from 'node:fs';import assert from 'node:assert/strict';
const css=fs.readFileSync('design-system.css','utf8'),index=fs.readFileSync('index.html','utf8');
for(const token of ['--surface-canvas','--text-primary','--accent-action','--space-4','--radius-panel','--elevation-panel'])assert.ok(css.includes(token),`Missing semantic token ${token}`);
assert.equal((index.match(/id="reportFab"/g)||[]).length,1,'Map must expose one primary report action');
assert.equal((index.match(/id="layersButton"/g)||[]).length,1,'Map filters must live behind one layers interaction');
const nav=index.match(/<nav class="bottom-nav[\s\S]*?<\/nav>/)?.[0]||'';
assert.match(nav,/<svg>/,'Bottom navigation must use the product icon system');
assert.doesNotMatch(nav,/🐾|🗺️|💬|🔔|🐶|🐈/,'Product navigation may not use emoji iconography');
const mapChrome=index.match(/<section id="view-map"[\s\S]*?<\/section>/)?.[0]||'';
assert.doesNotMatch(mapChrome,/⚠️|🌿|🚨|🐕/,'Permanent map controls may not use emoji iconography');
assert.match(css,/--accent-safe:#2f725f/,'Buurtspoor trust color missing');
assert.match(css,/--accent-action:#e8a62b/,'Buurtspoor report color missing');
assert.match(css,/@media\(max-width:380px\)/,'Small phone composition missing');
console.log('PASS Design QA Agent: semantic system, one map report action and small-phone composition');
