import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';

const mobile=fs.readFileSync('mobile-ui.js','utf8');
const profile=fs.readFileSync('profile-ui.js','utf8');
const dialog=fs.readFileSync('dialog-ui.js','utf8');
const community=fs.readFileSync('community-tools.js','utf8');
const hotfix=fs.readFileSync('ui-hotfix-1.6.2.js','utf8');
const bridge=fs.readFileSync('community-ui-bridge.js','utf8');
const reportPhoto=fs.readFileSync('report-photo.js','utf8');
const lifecycle=fs.readFileSync('report-lifecycle.js','utf8');
const versionFile=fs.readFileSync('version.js','utf8');
const index=fs.readFileSync('index.html','utf8');
for(const file of ['mobile-ui.js','profile-ui.js','dialog-ui.js','community-tools.js','ui-hotfix-1.6.2.js','report-photo.js','report-lifecycle.js']) execFileSync(process.execPath,['--check',file]);
const version=versionFile.match(/version:'(\d+\.\d+\.\d+)'/)?.[1];
assert.ok(version,'Central SemVer version missing');
assert.ok(mobile.includes('--wd-touch:44px'),'Touch target baseline must be 44px');
assert.ok(mobile.includes('safe-area-inset-bottom'),'Bottom safe area support missing');
assert.ok(dialog.includes('pointerdown'),'Dialogs must support pointer dragging');
assert.ok(profile.includes('#mapPlusBtn{display:none!important}'),'Duplicate map report plus must remain removed');
assert.ok(profile.includes('Eigen foto'),'Own dog photo option missing');
assert.ok(community.includes("removeAttribute('capture')"),'Avatar photo must allow album/library selection');
assert.ok(community.includes('reportDuration'),'Report duration field missing');
assert.ok(community.includes('reportAnnoyance'),'Report annoyance 1-5 field missing');
assert.ok(community.includes('shareMunicipalList'),'Municipal share/export missing');
assert.ok(community.includes('Bekijk meldingenlijst'),'In-app report list preview missing');
assert.ok(community.includes('chatDirectoryNote'),'Chat directory explanation missing');
assert.ok(community.includes('HIDDEN_CHATS_KEY'),'Persistent chat deletion missing');
assert.ok(hotfix.includes('removeFakeUnreadBadges'),'Fake default unread badges must be removed');
assert.ok(hotfix.includes('Foto verwijderen'),'Photo removal action must be explicit');
assert.ok(hotfix.includes('Verder met melding'),'Photo flow must provide a clear continuation action');
assert.ok(hotfix.includes("danger:'Gevaar'"),'Report type codes must be translated to Dutch');
assert.ok(hotfix.includes('setTextIfChanged'),'Hotfix text mutations must be idempotent');
assert.ok(hotfix.includes('scheduleReconcile'),'MutationObserver work must be scheduled and deduplicated');
assert.ok(bridge.includes(`community-tools.js?v=${version}`),`Community tools loader must match v${version}`);
assert.ok(bridge.includes('ui-hotfix-1.6.2.js?v=2'),'Stability hotfix loader missing');
assert.ok(reportPhoto.includes('reportPhotoInput'),'Report photo picker missing');
assert.ok(reportPhoto.includes('max=1280'),'Report photo resize cap missing');
assert.ok(reportPhoto.includes("toDataURL('image/jpeg',.82)"),'Report photo JPEG conversion missing');
assert.ok(reportPhoto.includes('Deel geen herkenbare personen'),'Report photo privacy guidance missing');
assert.ok(reportPhoto.includes('report-detail-photo'),'Report photo detail rendering missing');
assert.ok(lifecycle.includes('localOnlyFallback'),'Remote lifecycle must have a local fail-safe');
assert.ok(lifecycle.includes('Voor iedereen verwijderen lukt tijdelijk niet'),'Lifecycle fallback must tell the truth about global removal');
assert.ok(!index.includes('Rond jullie'),'Deprecated home heading must stay removed');
console.log(`PASS Mobile UX Agent v${version} stability, report photo flow and report lifecycle fallback`);
